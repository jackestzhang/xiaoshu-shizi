"""打包：校验 → 合成语音 → 生成 app/data.js + app/sprites.js。

草稿（status=draft）不允许打包，必须先 review.py --ok。
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import common
from common import PAGE_LIMIT
import sprites
import tts
import validate


def synth_all(lessons: list[dict], curriculum: dict) -> tuple[dict, int, int]:
    used = common.unique([ch for l in lessons for ch in common.lesson_chars(l)])
    char_meta, jobs = {}, []
    for ch in used:
        meta = curriculum[ch]
        jobs.append((ch, meta["word"]))
    total_chars = 0
    for ch, word in jobs:
        p1 = tts.synth(ch)
        p2 = tts.synth(word)
        char_meta[ch] = {
            "pinyin": curriculum[ch]["pinyin"],
            "word": word,
            "audio": f"assets/audio/{p1.name}",
            "wordAudio": f"assets/audio/{p2.name}",
            "status": curriculum[ch]["status"],
        }
        total_chars += 2
        print(f"  · {ch} / {word}", end="\r", flush=True)
        time.sleep(0.15)

    page_audio = {}
    for l in lessons:
        if l.get("kind") != "story":
            continue
        for i, page in enumerate(l.get("pages", []), 1):
            key = f"p:{l['id']}:{i}"
            path = tts.synth(page["text"])
            page_audio[key] = f"assets/audio/{path.name}"
            total_chars += 1
            print(f"  · 第{i}页整句", end="\r", flush=True)
            time.sleep(0.15)
    print(" " * 40, end="\r")
    return char_meta, page_audio, total_chars


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--allow-draft", action="store_true")
    args = ap.parse_args()

    curriculum = common.load_curriculum()
    lessons = common.load_lessons()
    if not lessons:
        common.die("没有课程")

    errors, notes = [], []
    for l in lessons:
        e, n = validate.check_lesson(l, lessons, curriculum, with_assets=False)
        errors += e
        notes += n
    if errors:
        for e in errors:
            print(f"  ✗ {e}", file=sys.stderr)
        common.die(f"{len(errors)} 个校验错误，未打包")

    drafts = [l["id"] for l in lessons if l.get("status") != "confirmed"]
    if drafts and not args.allow_draft:
        common.die(f"这些课还没确认文案：{' '.join(drafts)}。先跑 review.py --id <ID> --ok")

    draft_art = []
    for l in lessons:
        for i, page in enumerate(l.get("pages", []), 1):
            art = page.get("art")
            if art and art.get("status") != "approved":
                draft_art.append(f"{l['id']} 第{i}页")
    if draft_art and not args.allow_draft:
        common.die(f"这些插画还没确认：{'、'.join(draft_art)}。先看 art/<ID>/ 再跑 art.py --id <ID> --ok")

    long_pages = [f"{l['id']}({l['page_limit']}字/页)" for l in lessons
                  if l.get("page_limit") and l["page_limit"] > PAGE_LIMIT]
    if long_pages:
        print(f"  长页课程：{'、'.join(long_pages)}")
    print(f"校验通过（{len(notes)} 条提醒），开始合成语音")
    char_meta, page_audio, n = synth_all(lessons, curriculum)

    clean_lessons = []
    for l in lessons:
        d = {k: v for k, v in l.items() if not k.startswith("_")}
        if d.get("kind") == "story":
            for i, page in enumerate(d.get("pages", []), 1):
                page["audio"] = page_audio[f"p:{d['id']}:{i}"]
        clean_lessons.append(d)

    payload = {
        "lessons": clean_lessons,
        "chars": char_meta,
        "totalChars": len(char_meta),
    }
    data_js = "/* AUTO-GENERATED by pipeline/build.py — 不要手改 */\nwindow.SHIZI = " + \
        json.dumps(payload, ensure_ascii=False, indent=2) + ";\n"
    (common.APP / "data.js").write_text(data_js, encoding="utf-8")

    gen_sprites()

    # 回收没有被引用的音频（内容哈希命名，删除是安全的）
    used = {Path(m["audio"]).name for m in char_meta.values()}
    used |= {Path(m["wordAudio"]).name for m in char_meta.values()}
    used |= {Path(p).name for p in page_audio.values()}
    removed = 0
    for f in common.AUDIO.glob("*.mp3"):
        if f.name not in used:
            f.unlink()
            removed += 1

    # 回收没有课程引用的插画
    art_dir = common.APP / "assets" / "art"
    used_art = {
        Path(page["art"]["file"]).name
        for l in lessons for page in l.get("pages", []) if page.get("art")
    }
    removed_art = 0
    if art_dir.exists():
        for f in art_dir.glob("*.webp"):
            if f.name not in used_art:
                f.unlink()
                removed_art += 1

    audio_bytes = sum(p.stat().st_size for p in common.AUDIO.glob("*.mp3"))
    app_bytes = sum(p.stat().st_size for p in common.APP.rglob("*") if p.is_file())
    print(f"\n✓ 打包完成：{len(lessons)} 节课 · {len(char_meta)} 字 · {n} 段语音")
    if removed:
        print(f"  回收了 {removed} 段未引用音频")
    if removed_art:
        print(f"  回收了 {removed_art} 张未引用插画")
    print(f"  音频 {audio_bytes/1024:.0f} KB · 整个 app/ {app_bytes/1024:.0f} KB")
    print(f"  打开 app/index.html")


def gen_sprites() -> None:
    out = ["/* AUTO-GENERATED by pipeline/sprites.py — 不要手改 */", "window.SPRITES = {"]
    for k, v in sprites.SPRITES.items():
        out.append(f"  {json.dumps(k)}: `{v}`,")
    out.append("};")
    out.append("window.SPRITE_CHAR = " + json.dumps(sprites.SPRITE_CHAR, ensure_ascii=False) + ";")
    out.append("window.LAYOUT = " + json.dumps(sprites.LAYOUT, ensure_ascii=False) + ";")
    out.append("window.BASE_SIZE = " + json.dumps(sprites.BASE_SIZE, ensure_ascii=False) + ";")
    (common.APP / "sprites.js").write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
